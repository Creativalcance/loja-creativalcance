export type SalesCopy = { [K in keyof typeof rows]: string };
export function salesCopy(locale: SiteLocale): SalesCopy {
  const index = Object.keys(SITE_LOCALES).indexOf(locale);
  return Object.fromEntries(
    Object.entries(rows).map(([k, v]) => [k, v[index]]),
  ) as SalesCopy;
}
export function salesMoney(
  cents: number,
  currency = "EUR",
  locale: SiteLocale = "pt",
) {
  return new Intl.NumberFormat(SITE_LOCALES[locale].intlLocale, {
    style: "currency",
    currency,
  }).format(cents / 100);
}
export function countryName(code: string, locale: SiteLocale = "pt") {
  return new Intl.DisplayNames([locale], { type: "region" }).of(code) || code;
}
